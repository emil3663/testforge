"""
TestForge — AI-native test automation assistant.

Runs as a FastAPI web application.
Start with: uvicorn app:app --reload
"""

from __future__ import annotations

import os
import subprocess
import time
import uuid
from pathlib import Path

from dotenv import load_dotenv
from fastapi import FastAPI
from fastapi.responses import HTMLResponse, JSONResponse
from fastapi.staticfiles import StaticFiles
from openai import OpenAI
from pydantic import BaseModel

load_dotenv()

app = FastAPI(title="TestForge", version="1.0.0")

# ---------------------------------------------------------------------------
# Static files & templates
# ---------------------------------------------------------------------------

STATIC_DIR = Path(__file__).parent / "static"
TEMPLATES_DIR = Path(__file__).parent / "templates"
RUNS_DIR = Path(__file__).parent / "runs"

if STATIC_DIR.exists():
    app.mount("/static", StaticFiles(directory=str(STATIC_DIR)), name="static")

RUNS_DIR.mkdir(exist_ok=True)

# ---------------------------------------------------------------------------
# System prompt — produces Python pytest-playwright tests
# ---------------------------------------------------------------------------

SYSTEM_PROMPT = """\
You are TestForge, an expert Playwright test-automation engineer specialising in Python.
Your job is to translate a plain-English test description into a clean, idiomatic Python
test file using pytest and pytest-playwright.

Rules:
- Import Page and expect from playwright.sync_api.
- Use the sync Playwright API with pytest fixtures (def test_...(page: Page):).
- Use the base URL provided by the user directly in page.goto() calls (full absolute URLs).
- Write descriptive test function names in snake_case that a non-developer tester can read.
- Add clear inline comments explaining each step so the tester can learn from the code.
- Prefer user-visible locators: page.get_by_role(), page.get_by_label(),
  page.get_by_placeholder(), page.get_by_text().
- Write assertions using expect() that verify visible, user-facing outcomes.
- Cover every scenario mentioned in the description (happy path and error cases).
- Keep the code concise and complete — no TODO stubs or placeholder code.
- Output ONLY the Python code. Do not include markdown fences or explanations.
"""


def _mock_generate(base_url: str, description: str) -> str:
    """Return a sample test when OPENAI_API_KEY is not set."""
    safe_desc = description[:80].replace("'", "\\'")
    return f'''\
from playwright.sync_api import Page, expect


# Generated by TestForge for: {safe_desc}


def test_page_loads(page: Page) -> None:
    """Verify the application homepage loads and shows content."""
    # Navigate to the base URL
    page.goto("{base_url}")

    # Confirm the page title is set
    expect(page).to_have_title(/.+/)

    # Confirm the main content area is visible
    expect(page.locator("body")).to_be_visible()


def test_core_elements_present(page: Page) -> None:
    """Check that the page renders at least one heading."""
    page.goto("{base_url}")

    # Wait for the page to settle before checking layout
    page.wait_for_load_state("networkidle")

    # Verify at least one heading element is visible
    expect(page.get_by_role("heading").first).to_be_visible()


# NOTE: This is a sample test — no OPENAI_API_KEY was found.
# Add your key to .env to generate tests tailored to your description.
'''


# ---------------------------------------------------------------------------
# Request / Response models
# ---------------------------------------------------------------------------


class GenerateRequest(BaseModel):
    baseUrl: str = "http://localhost"
    description: str


class RunRequest(BaseModel):
    code: str


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------


@app.get("/", response_class=HTMLResponse)
async def index() -> HTMLResponse:
    html = (TEMPLATES_DIR / "index.html").read_text(encoding="utf-8")
    return HTMLResponse(content=html)


@app.post("/api/generate")
async def generate(req: GenerateRequest) -> JSONResponse:
    if not req.description.strip():
        return JSONResponse({"error": "description is required"}, status_code=400)

    api_key = os.getenv("OPENAI_API_KEY")

    if not api_key:
        code = _mock_generate(req.baseUrl, req.description)
        return JSONResponse({"code": code})

    client = OpenAI(api_key=api_key)
    chat = client.chat.completions.create(
        model="gpt-4o",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": (
                    f"Base URL: {req.baseUrl}\n\n"
                    f"Test description:\n{req.description}"
                ),
            },
        ],
        temperature=0.2,
    )
    code = chat.choices[0].message.content or ""
    return JSONResponse({"code": code})


@app.post("/api/run")
async def run(req: RunRequest) -> JSONResponse:
    if not req.code.strip():
        return JSONResponse({"error": "code is required"}, status_code=400)

    test_file = RUNS_DIR / f"test_{uuid.uuid4().hex[:12]}.py"
    try:
        test_file.write_text(req.code, encoding="utf-8")

        start = time.monotonic()
        result = subprocess.run(
            [
                "python",
                "-m",
                "pytest",
                str(test_file),
                "--tb=short",
                "-v",
                "--no-header",
                "--browser=chromium",
            ],
            capture_output=True,
            text=True,
            timeout=120,
        )
        duration_ms = int((time.monotonic() - start) * 1000)

        output = (result.stdout + result.stderr).strip()
        passed = result.returncode == 0

        return JSONResponse(
            {"passed": passed, "output": output, "duration": duration_ms}
        )
    except subprocess.TimeoutExpired:
        return JSONResponse({"error": "Test timed out after 120 seconds"}, status_code=504)
    finally:
        test_file.unlink(missing_ok=True)
