/**
 * Phase 35 (TFP-132, Decision 1): POST /api/generate and POST /api/run with a
 * run mode. Absent is a Standard run, unchanged; a Comprehensive request
 * gets its own suite for every known page up to the cap; an invalid one is
 * refused rather than run as something else.
 *
 * Run via:
 * node --import ./scripts/register-node-test-ts-resolver.mjs --experimental-strip-types --test src/app/api/generate/route.comprehensive.test.ts
 */
import assert from "node:assert";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, test } from "node:test";
import { chatBodies, completion, fakeBaseUrl, fakeOpenAi, installFakeServer, json } from "./route-test-helpers.ts";

const scratchRoot = mkdtempSync(join(tmpdir(), "testforge-comprehensive-route-test-"));
process.env.TESTFORGE_RUNS_ROOT = join(scratchRoot, "runs");
after(() => rmSync(scratchRoot, { recursive: true, force: true }));

const { POST: generate } = await import("./route.ts");
const { POST: run } = await import("../run/route.ts");
const { NextRequest } = await import("next/server");
const { findTypeErrors } = await import("../../../lib/generate/validate.ts");

installFakeServer();

function post(url: string, body: unknown) {
    return new NextRequest(new URL(url), { method: "POST", body: JSON.stringify(body), headers: { "content-type": "application/json" } });
}

const ORIGIN = "https://site.test";
const PROFILE = {
    scannedAt: "2026-09-30T00:00:00.000Z",
    baseUrl: ORIGIN,
    pages: ["/", "/login", "/about"].map((path) => ({ path, url: `${ORIGIN}${path}`, title: "", metaDescription: "", headings: [], buttons: [], links: [], visibleTextSnippets: [] })),
};

function generateBody(runMode?: unknown) {
    return { baseUrl: ORIGIN, description: "Check the site.", selectedPractices: ["security"], contentProfile: PROFILE, autoInspect: false, ...(runMode === undefined ? {} : { runMode }) };
}

test("generate: a Comprehensive security request returns its own suite, the page scope and the run mode", async () => {
    const body = await (await generate(post("http://localhost/api/generate", generateBody({ kind: "comprehensive", area: "security", pageCap: 2 })))).json();
    assert.equal(body.generatedBy, "template");
    assert.deepEqual(body.runMode, { kind: "comprehensive", area: "security", level: "passive", pageCap: 2 });
    assert.deepEqual(body.pageScope, { covered: ["/", "/login"], notCovered: ["/about"], pageCap: 2 });
    assert.match(body.code, /Generated by TestForge: Comprehensive security \(passive\) run\./);
    assert.deepEqual(findTypeErrors(body.code), []);
});

// --- TFP-135 (Decision 5): the local model's scenarios ------------------------

const LOCAL_MODEL = "testforge-qwen7b";
const CATALOG_ID = `${LOCAL_MODEL}:latest`;
const SCENARIO = [
    "import { test, expect } from '@playwright/test';",
    "test('the login page has a heading', async ({ page }) => {",
    "  await page.goto('/login');",
    "  await expect(page.locator('h1')).toBeVisible();",
    "});",
].join("\n");

function useOllama() {
    process.env.TESTFORGE_OLLAMA_MODEL = LOCAL_MODEL;
    process.env.TESTFORGE_OLLAMA_BASE_URL = fakeBaseUrl();
}

async function comprehensive(area: string) {
    return (await generate(post("http://localhost/api/generate", generateBody({ kind: "comprehensive", area })))).json();
}

test("TFP-135: with a local model, a Comprehensive request asks it for that area alone and appends its scenarios in their own block", async () => {
    const templateOnly = await comprehensive("accessibility");
    fakeOpenAi([CATALOG_ID], (_req, res) => json(res, 200, completion(SCENARIO)));
    useOllama();
    const body = await comprehensive("accessibility");
    assert.equal(body.generatedBy, "template+ollama");
    assert.equal(body.model, CATALOG_ID);
    assert.ok(body.code.startsWith(templateOnly.code), "the template's suite is kept whole, first");
    assert.match(body.code, /test\.describe\('Local model \(testforge-qwen7b:latest\)', \{ annotation: \{ type: 'gate', description: 'interactive' \} \}, \(\) => \{\n {4}test\.skip\(process\.env\.TESTFORGE_INTERACTIVE !== '1', 'written by the local model \(testforge-qwen7b:latest\): it may submit forms/);
    assert.deepEqual(findTypeErrors(body.code), []);
    assert.equal(chatBodies.length, 1);
    const user = chatBodies[0].messages?.find((m) => m.role === "user")?.content ?? "";
    assert.match(user, /Selected best-practice coverage: accessibility\n/, "Phase 37's plain request for the one area");
    assert.deepEqual(body.gates.map((g: { gate: string; verdict: string }) => `${g.gate}: ${g.verdict}`), ["time budget: kept", "type check: kept", "unawaited assertions: kept", "promise to plain matcher: kept", "duplicate tests: kept", "merged suite type check: kept"]);
});

test("TFP-135, TFP-146: in a passive security run the model's scenarios are at the active gate, so never run - they may send input", async () => {
    fakeOpenAi([CATALOG_ID], (_req, res) => json(res, 200, completion(SCENARIO)));
    useOllama();
    const body = await comprehensive("security");
    assert.equal(body.generatedBy, "template+ollama");
    assert.match(body.code, /test\.describe\('Local model \(testforge-qwen7b:latest\)', \{ annotation: \{ type: 'gate', description: 'active' \} \}, \(\) => \{\n {4}test\.skip\(true, 'attack-shaped input: needs the ownership confirmation, not built yet'\);/);
});

test("TFP-135: a rejected model suite leaves the template's suite alone, labelled with why", async (t) => {
    t.mock.method(console, "error", () => {});
    const templateOnly = await comprehensive("accessibility");
    fakeOpenAi([CATALOG_ID], (_req, res) => json(res, 200, completion(SCENARIO.replace("toBeVisible()", "toBeAccessible()"))));
    useOllama();
    const body = await comprehensive("accessibility");
    assert.equal(body.generatedBy, "fallback");
    assert.equal(body.fallbackReason, "invalid_output");
    assert.equal(body.code, templateOnly.code);
});

test("TFP-135: with no local model configured, the template's suite alone, and the model is not called", async () => {
    const body = await comprehensive("security");
    assert.equal(body.generatedBy, "template");
    assert.equal(body.model, undefined);
    assert.equal(chatBodies.length, 0);
});

test("generate: a Standard request - no run mode, or { kind: 'standard' } - is answered exactly as before", async () => {
    const before = await (await generate(post("http://localhost/api/generate", generateBody()))).json();
    const explicit = await (await generate(post("http://localhost/api/generate", generateBody({ kind: "standard" })))).json();
    // Phase 42 (TFP-190): the one addition is what the site suite reused; the second request finds the first's saved suite.
    assert.deepEqual(Object.keys(before), ["code", "siteSuite"]);
    assert.equal(explicit.code, before.code);
    assert.equal(explicit.siteSuite.store, before.siteSuite.store, "no run mode and { kind: 'standard' } are the same suite");
});

test("generate and run: an invalid run mode is refused with 400, never run as a different run", async () => {
    for (const runMode of [{ kind: "comprehensive", area: "seo/content" }, { kind: "comprehensive", area: "security", level: "active" }, { kind: "comprehensive", area: "security", pageCap: 0 }]) {
        const generated = await generate(post("http://localhost/api/generate", generateBody(runMode)));
        assert.equal(generated.status, 400, JSON.stringify(runMode));
        const started = await run(post("http://localhost/api/run", { code: "import { test } from '@playwright/test';\ntest('a', async () => {});", baseUrl: ORIGIN, runMode }));
        assert.equal(started.status, 400, JSON.stringify(runMode));
        assert.match((await started.json()).error, /runMode|passive/);
    }
});

test("run: a Comprehensive run needs a base URL", async () => {
    const response = await run(post("http://localhost/api/run", { code: "import { test } from '@playwright/test';\ntest('a', async () => {});", runMode: { kind: "comprehensive", area: "security" } }));
    assert.equal(response.status, 400);
    assert.match((await response.json()).error, /baseUrl is required for a Comprehensive run/);
});
