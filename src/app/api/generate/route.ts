import { NextRequest, NextResponse } from "next/server";
import OpenAI from "openai";

const SYSTEM_PROMPT = `You are TestForge, an expert Playwright test automation engineer.
Your job is to translate a plain-English test description into a clean, idiomatic Playwright TypeScript test file.

Rules:
- Use @playwright/test imports (test, expect).
- Use the base URL provided by the user as the starting point.
- Write descriptive test names that a non-developer tester could understand.
- Add clear comments explaining each step so the tester can learn from the code.
- Prefer user-visible locators (getByRole, getByLabel, getByPlaceholder, getByText) over CSS selectors.
- Include assertions that verify visible outcomes, not implementation details.
- Handle happy-path and any failure scenarios mentioned in the description.
- Keep the code concise but complete — no TODO stubs.
- Output ONLY the TypeScript code. Do not include markdown fences or explanations.`;

/**
 * Generates a sample Playwright test when no OPENAI_API_KEY is configured.
 * This lets developers run the app locally without an API key during development.
 */
function mockGenerate(baseUrl: string, description: string): string {
  return `import { test, expect } from '@playwright/test';

// Generated by TestForge for: ${description.slice(0, 80)}

test.describe('TestForge generated suite', () => {
  test.use({ baseURL: '${baseUrl}' });

  test('verifies the page loads correctly', async ({ page }) => {
    // Navigate to the base URL
    await page.goto('/');

    // Confirm the page title is not empty
    await expect(page).toHaveTitle(/.+/);

    // Confirm the main content area is visible
    await expect(page.locator('body')).toBeVisible();
  });

  test('checks for core page elements', async ({ page }) => {
    await page.goto('/');

    // Wait for network idle so dynamic content loads
    await page.waitForLoadState('networkidle');

    // Verify at least one heading is present
    const headings = page.getByRole('heading');
    await expect(headings.first()).toBeVisible();
  });
});

// NOTE: This is a sample test generated without an OpenAI API key.
// Set OPENAI_API_KEY in your .env.local to generate tests tailored to your description.`;
}

export async function POST(req: NextRequest) {
  const { baseUrl, description } = await req.json();

  if (!description || typeof description !== "string") {
    return NextResponse.json(
      { error: "description is required" },
      { status: 400 }
    );
  }

  const apiKey = process.env.OPENAI_API_KEY;

  if (!apiKey) {
    const code = mockGenerate(baseUrl ?? "https://example.com", description);
    return NextResponse.json({ code });
  }

  const client = new OpenAI({ apiKey });

  const chat = await client.chat.completions.create({
    model: "gpt-4o",
    messages: [
      { role: "system", content: SYSTEM_PROMPT },
      {
        role: "user",
        content: `Base URL: ${baseUrl ?? "https://example.com"}\n\nTest description:\n${description}`,
      },
    ],
    temperature: 0.2,
  });

  const code = chat.choices[0]?.message?.content ?? "";
  return NextResponse.json({ code });
}
