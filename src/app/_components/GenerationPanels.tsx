import { ReportPanel } from "@/app/_components/ReportPanel";
import { describePageInspection } from "@/lib/report/page-inspection-text";
import { describeSiteSuite } from "@/lib/report/site-suite-text";
import type { RunReport } from "@/lib/report/types";

interface GenerationPanelsProps {
    report: RunReport;
}

// Phase 34 (TFP-119). Decision 7: every area in scope with no test says why.
// Decision 8: every generation gate's verdict is shown with its bar, the
// measured result and the evidence, so a decision to keep or drop local-model
// output can be argued with a recorded number rather than a guess.
export function GenerationPanels({ report }: GenerationPanelsProps) {
    const emptyAreas = report.emptyAreas ?? [];
    const generation = report.generation ?? null;

    if (emptyAreas.length === 0 && !generation) {
        return null;
    }

    return (
        <>
            {emptyAreas.length > 0 ? (
                <ReportPanel
                    eyebrow="Coverage Gaps"
                    title="Areas with no tests"
                    description="Areas this run was asked to cover that ended up with no test at all, and why."
                >
                    <ul className="space-y-3">
                        {emptyAreas.map((item) => (
                            <li key={item.area} className="rounded-2xl border border-zinc-200 bg-zinc-50 p-4">
                                <div className="font-semibold text-zinc-900">{item.area}</div>
                                <ul className="mt-1 list-disc space-y-1 pl-5 text-sm leading-6 text-zinc-600">
                                    {item.reasons.map((reason) => (
                                        <li key={reason}>{reason}</li>
                                    ))}
                                </ul>
                            </li>
                        ))}
                    </ul>
                </ReportPanel>
            ) : null}

            {generation ? (
                <ReportPanel
                    eyebrow="Generation"
                    title="How this suite was generated"
                    description="Which generator wrote the suite, and each check the local model's tests had to pass."
                >
                    <p className="text-sm leading-6 text-zinc-600">
                        Generated by <span className="font-semibold text-zinc-900">{generation.generatedBy}</span>
                        {generation.model ? ` (${generation.model})` : ""}
                        {generation.gapFill && generation.gapFill.gapAreas.length > 0
                            ? `; the local model was asked for ${generation.gapFill.gapAreas.join(", ")} - ${generation.gapFill.outcome}`
                            : ""}
                        {generation.fallbackReason ? ` (${generation.fallbackReason})` : ""}.
                    </p>
                    {generation.pageInspection ? (
                        <p className="mt-2 text-sm leading-6 text-zinc-600">{describePageInspection(generation.pageInspection)}</p>
                    ) : null}
                    {generation.siteSuite ? (
                        <p className="mt-2 text-sm leading-6 text-zinc-600">{describeSiteSuite(generation.siteSuite)}</p>
                    ) : null}
                    {generation.gates.length > 0 ? (
                        <div className="mt-4 overflow-x-auto">
                            <table className="min-w-full text-left text-sm">
                                <thead className="text-xs uppercase tracking-[0.12em] text-zinc-500">
                                    <tr>
                                        <th className="py-2 pr-4">Check</th>
                                        <th className="py-2 pr-4">Bar</th>
                                        <th className="py-2 pr-4">Measured</th>
                                        <th className="py-2 pr-4">Verdict</th>
                                        <th className="py-2">Evidence</th>
                                    </tr>
                                </thead>
                                <tbody className="text-zinc-700">
                                    {generation.gates.map((gate) => (
                                        <tr key={gate.gate} className="border-t border-zinc-200 align-top">
                                            <td className="py-2 pr-4 font-medium">{gate.gate}</td>
                                            <td className="py-2 pr-4">{gate.bar}</td>
                                            <td className="py-2 pr-4">{gate.measured}</td>
                                            <td className={`py-2 pr-4 font-semibold ${gate.verdict === "kept" ? "text-emerald-700" : "text-rose-700"}`}>{gate.verdict}</td>
                                            <td className="py-2 font-mono text-xs">{gate.evidence.length > 0 ? gate.evidence.join("\n") : "-"}</td>
                                        </tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    ) : null}
                </ReportPanel>
            ) : null}
        </>
    );
}
